import 'package:flutter/widgets.dart';

/// Lightweight UI localization (no code generation). UI text exists in English and Filipino;
/// other languages fall back to English for menus while AI explanations use the chosen language.
class StringsScope extends InheritedWidget {
  const StringsScope({super.key, required this.code, required super.child});
  final String code;

  static String of(BuildContext c) => c.dependOnInheritedWidgetOfExactType<StringsScope>()?.code ?? 'en';

  @override
  bool updateShouldNotify(StringsScope old) => old.code != code;
}

extension TrX on BuildContext {
  String tr(String key) {
    final code = StringsScope.of(this);
    return _strings[code]?[key] ?? _strings['en']![key] ?? key;
  }
}

String uiCodeFor(String? languageCode) => (languageCode == 'fil' || languageCode == 'tl') ? 'fil' : 'en';

String greetingKey() {
  final h = DateTime.now().hour;
  if (h < 12) return 'greet_morning';
  if (h < 18) return 'greet_afternoon';
  return 'greet_evening';
}

